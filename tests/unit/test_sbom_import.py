# hostile and broken input


def test_not_json_and_wrong_top_level() -> None:
    for data in (b"", b"{broken", b"<bom/>", b"[1,2]", b'"text"', b"null"):
        with pytest.raises(SbomNotJsonError):
            parse_sbom(data)


def test_deeply_nested_json_is_rejected_cleanly() -> None:
    with pytest.raises(SbomNotJsonError):
        parse_sbom(b"[" * 200_000 + b"]" * 200_000)
    with pytest.raises(SbomLimitError, match="nested"):
        parse_sbom(b'{"a":' * 100_000 + b"1" + b"}" * 100_000)


def test_nul_characters_are_rejected() -> None:
    raw = json.dumps(bom([comp("a")])).replace('"a"', '"a\\u0000"').encode()
    with pytest.raises(SbomNotJsonError, match="NUL"):
        parse_sbom(raw)


def test_size_limit() -> None:
    data = json.dumps(bom([comp("a")])).encode()
    with pytest.raises(SbomTooLargeError):
        parse_sbom(data, SbomLimits(max_bytes=len(data) - 1))
    assert parse_sbom(data, SbomLimits(max_bytes=len(data))).components


@pytest.mark.parametrize(
    ("patch", "message"),
    [
        ({"bomFormat": "SPDX"}, "bomFormat"),
        ({"specVersion": "1.3"}, "specVersion"),
        ({"specVersion": "2.0"}, "specVersion"),
        ({"specVersion": 1.6}, "specVersion"),
    ],
)
def test_unsupported_formats_and_versions(patch: dict[str, Any], message: str) -> None:
    doc = bom([comp("a")])
    doc.update(patch)
    with pytest.raises(SbomUnsupportedError, match=message):
        parse(doc)


def test_schema_violations_are_reported_with_paths() -> None:
    doc = bom([comp("a")])
    del doc["components"][0]["name"]
    doc["components"][0]["type"] = "gadget"
    with pytest.raises(SbomSchemaError) as exc:
        parse(doc)
    assert any("components/0" in p for p in exc.value.problems)
    assert len(exc.value.problems) <= 5


def test_schema_is_enforced_per_declared_version() -> None:
    doc = bom([comp("a")], spec="1.4")
    doc["metadata"] = {"component": {"type": "application", "name": "x", "unknownField": 1}}
    with pytest.raises(SbomSchemaError):
        parse(doc)


def test_component_count_limit() -> None:
    with pytest.raises(SbomLimitError, match="components"):
        parse(bom([comp(f"c{i}") for i in range(11)]), max_components=10)
    assert len(parse(bom([comp(f"c{i}") for i in range(10)]), max_components=10).components) == 10


def test_nesting_depth_limit_without_recursion() -> None:
    def nest(depth: int) -> dict[str, Any]:
        node = comp("leaf")
        for i in range(depth):
            node = comp(f"n{i}", ref=f"n{i}", components=[node])
        return node

    with pytest.raises(SbomLimitError, match="nested"):
        parse(bom([nest(40)]), max_depth=32)
    assert len(parse(bom([nest(5)]), max_depth=32).components) == 6


def test_extremely_deep_nesting_is_limited_not_crashing() -> None:
    node: dict[str, Any] = comp("leaf")
    for i in range(500):
        node = {"type": "library", "name": f"n{i}", "components": [node]}
    with pytest.raises(SbomLimitError):
        parse(bom([node]))


def test_input_is_not_mutated_and_document_is_kept_for_storage() -> None:
    doc = bom([comp("a")])
    before = copy.deepcopy(doc)
    parsed = parse(doc)
    assert doc == before
    assert parsed.document == before
