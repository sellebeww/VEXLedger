SBOMS = Path(__file__).parents[1] / "fixtures" / "sboms"


def bom(
    components: list[dict[str, Any]] | None = None,
    deps: list[dict[str, Any]] | None = None,
    root: dict[str, Any] | None = None,
    spec: str = "1.6",
) -> dict[str, Any]:
    """A hand-built (synthetic) valid CycloneDX document."""
    doc: dict[str, Any] = {"bomFormat": "CycloneDX", "specVersion": spec, "version": 1}
    if root:
        doc["metadata"] = {"component": root}
    if components is not None:
        doc["components"] = components
    if deps is not None:
        doc["dependencies"] = deps
    return doc


def comp(
    name: str, version: str = "1.0", purl: str | None = "auto", ref: str | None = "auto", **kw: Any
) -> dict[str, Any]:
    c: dict[str, Any] = {"type": "library", "name": name, "version": version}
    if purl == "auto":
        purl = f"pkg:pypi/{name}@{version}"
    if ref == "auto":
        ref = f"{name}@{version}"
    if purl:
        c["purl"] = purl
    if ref:
        c["bom-ref"] = ref
    c.update(kw)
    return c


def parse(doc: dict[str, Any], **limits: int):  # type: ignore[no-untyped-def]
    return parse_sbom(json.dumps(doc).encode(), SbomLimits(**limits) if limits else SbomLimits())


def codes(parsed) -> Counter[str]:  # type: ignore[no-untyped-def]
    return Counter(w.code for w in parsed.warnings)


# real SBOMs generated by cyclonedx-py


@pytest.mark.parametrize(
    ("name", "spec", "has_root"),
    [
        ("uv-env-1.4", "1.4", False),
        ("uv-env-1.5", "1.5", False),
        ("uv-env-1.6", "1.6", False),
        ("uv-env-1.6-with-root", "1.6", True),
    ],
)
def test_real_sboms_from_cyclonedx_py_import(name: str, spec: str, has_root: bool) -> None:
    data = (SBOMS / f"{name}.cdx.json").read_bytes()
    parsed = parse_sbom(data)
    assert parsed.spec_version == spec
    assert len(parsed.components) >= 90
    assert all(
        c.component_ref and c.ecosystem == "PyPI" for c in parsed.components if not c.no_purl
    )
    assert (parsed.root is not None) is has_root
    assert len(parsed.edges) > 90  # the dependency graph came through
    assert ("no_root_component" in codes(parsed)) is (not has_root)
    assert parsed.sha256 and parsed.size_bytes == len(data)
    assert all(a != b for a, b in parsed.edges)


def test_real_sbom_root_has_edges_to_its_direct_dependencies() -> None:
    parsed = parse_sbom((SBOMS / "uv-env-1.6-with-root.cdx.json").read_bytes())
    root = parsed.root
    assert root is not None and root.name == "vexledger"
    direct = {c for p, c in parsed.edges if p == root.index}
    assert len(direct) >= 10
    assert not root.unsupported_ecosystem  # the root is not reported as an unmatchable component


def test_pypi_names_are_normalized_from_real_data() -> None:
    parsed = parse_sbom((SBOMS / "uv-env-1.6.cdx.json").read_bytes())
    refs = {c.component_ref for c in parsed.components}
    assert "pypi/sqlalchemy@2.0.57" in refs  # source says SQLAlchemy
    assert all(r is None or r == r.lower() or "@" in r for r in refs)


# structure


def test_nested_components_are_flattened_and_edges_resolve() -> None:
    inner = comp("inner", "3.0")
    outer = comp("outer", "2.0", components=[inner])
    doc = bom(
        [outer],
        [{"ref": "outer@2.0", "dependsOn": ["inner@3.0"]}],
        root=comp("app", "1.0", purl="pkg:generic/app@1.0", ref="app@1.0"),
    )
    doc["dependencies"].append({"ref": "app@1.0", "dependsOn": ["outer@2.0"]})
    parsed = parse(doc)
    assert {c.name for c in parsed.components} == {"app", "outer", "inner"}
    by_name = {c.name: c.index for c in parsed.components}
    assert sorted(parsed.edges) == sorted(
        [(by_name["outer"], by_name["inner"]), (by_name["app"], by_name["outer"])]
    )
    assert parsed.root is not None and parsed.root.name == "app"


def test_hashes_prefer_sha256_and_are_lowercased() -> None:
    hashes = [
        {"alg": "SHA-1", "content": "a" * 40},
        {"alg": "SHA-256", "content": "B" * 64},
        {"alg": "MD5", "content": "c" * 32},
    ]
    parsed = parse(bom([comp("h", hashes=hashes)]))
    assert parsed.components[0].component_hash == "sha256:" + "b" * 64


def test_extract_hash_fallbacks() -> None:
    assert extract_hash([{"alg": "SHA-1", "content": "AB" * 20}]) == "sha1:" + "ab" * 20
    assert (
        extract_hash(
            [{"alg": "SHA-512", "content": "1" * 128}, {"alg": "SHA-1", "content": "2" * 40}]
        )
        == "sha512:" + "1" * 128
    )
    assert extract_hash([]) is None
    assert extract_hash("nope") is None
    assert extract_hash([{"alg": "SHA-256"}]) is None


def test_duplicates_by_purl_and_by_bom_ref_are_merged() -> None:
    a = comp("dup", "1.0", ref="ref-a")
    b = comp("dup", "1.0", ref="ref-b")  # same purl and version, other bom-ref
    c = comp("other", "1.0", purl="pkg:pypi/different@1.0", ref="ref-a")  # same bom-ref, other purl
    parsed = parse(
        bom(
            [a, b, c],
            [{"ref": "ref-b", "dependsOn": ["ref-a"]}, {"ref": "ref-b", "dependsOn": ["ref-b"]}],
        )
    )
    assert len(parsed.components) == 1
    assert sorted(parsed.components[0].bom_refs) == ["ref-a", "ref-b"]
    got = codes(parsed)
    assert got["duplicate_component_merged"] == 2
    assert got["duplicate_bom_ref_different_purl"] == 1
    assert got["self_dependency"] >= 1
    assert parsed.edges == []  # both refs are the same component after the merge


def test_duplicate_with_conflicting_hash_warns_and_first_wins() -> None:
    h1 = [{"alg": "SHA-256", "content": "1" * 64}]
    h2 = [{"alg": "SHA-256", "content": "2" * 64}]
    parsed = parse(bom([comp("d", ref="r1", hashes=h1), comp("d", ref="r2", hashes=h2)]))
    assert parsed.components[0].component_hash == "sha256:" + "1" * 64
    assert "duplicate_hash_conflict" in codes(parsed)


def test_duplicate_fills_a_missing_hash() -> None:
    h = [{"alg": "SHA-256", "content": "3" * 64}]
    parsed = parse(bom([comp("d", ref="r1"), comp("d", ref="r2", hashes=h)]))
    assert parsed.components[0].component_hash == "sha256:" + "3" * 64


def test_components_without_purl_or_with_unusable_purl_are_kept_and_flagged() -> None:
    doc = bom(
        [
            comp("nopurl", purl=None),
            comp("bad", purl="not-a-purl"),
            comp("noversion", version="", purl="pkg:pypi/noversion"),
            comp("deb", purl="pkg:deb/debian/curl@7.0"),
            comp("fine", "2.0"),
        ]
    )
    doc["components"][2].pop("version")
    parsed = parse(doc)
    by = {c.name: c for c in parsed.components}
    assert len(parsed.components) == 5  # nothing was dropped
    assert by["nopurl"].no_purl and by["nopurl"].purl_normal is None
    assert by["bad"].no_purl and by["bad"].purl_original == "not-a-purl"
    assert by["noversion"].no_purl and by["noversion"].component_ref is None
    assert (
        by["deb"].unsupported_ecosystem
        and by["deb"].component_ref == "deb/debian/curl@7.0"
        and by["deb"].ecosystem is None
    )
    assert not by["fine"].no_purl and by["fine"].ecosystem == "PyPI"
    got = codes(parsed)
    assert (
        got["no_purl"] == 1
        and got["invalid_purl"] == 1
        and got["purl_without_version"] == 1
        and got["unsupported_ecosystem"] == 1
    )


def test_purl_version_handling() -> None:
    parsed = parse(
        bom([comp("a", "1.0", purl="pkg:pypi/a"), comp("b", "2.0", purl="pkg:pypi/b@3.0")])
    )
    by = {c.name: c for c in parsed.components}
    assert by["a"].component_ref == "pypi/a@1.0"  # version taken from the component
    assert by["b"].component_ref == "pypi/b@3.0"  # purl wins
    got = codes(parsed)
    assert got["purl_version_from_component"] == 1 and got["purl_version_mismatch"] == 1


